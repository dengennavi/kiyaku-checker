// LINE返信文のテスト（node test.js）
import { replyFor, HELP } from "./src/format.js";
let fail = 0;
const ok = (c, m) => { console.log((c ? "  ✔ " : "  ✘ ") + m); if (!c) fail++; };
const demo = replyFor("デモ");
console.log(demo);
ok(demo.includes("🔴要確認 2件") && demo.includes("猫"), "「デモ」で猫の条項が🔴");
ok(demo.length < 5000, "LINEの文字数上限（5000）以内");
ok(replyFor("こんにちは") === HELP, "短い文は使い方を返す");
const normal = replyFor("第1条（適用）\n本規約は本サービスの利用に適用されます。\n第2条（料金）\n本サービスは無料でご利用いただけます。解約手数料はかかりません。");
ok(normal.includes("見つかりませんでした"), "該当なしの規約");
ok(replyFor("お問い合わせ").includes("@kiyaku_checker"), "問い合わせはXのDMを案内");
const subs = replyFor("2026/09/03 NETFLIX.COM 1,590\n2026/09/05 APPLE.COM/BILL 400\n2026/10/03 NETFLIX.COM 1,590\n2026/10/12 ｱﾄﾞﾋﾞ 2,380");
console.log(subs);
ok(subs.includes("見つかったサブスク：3件") && subs.includes("毎月払っているかも"), "明細を貼るとサブスクを返す");
ok(subs.includes("services/netflix.html"), "規約まとめページへのリンク");
ok(replyFor("サブスク").includes("サブスク発見の使い方"), "「サブスク」で使い方");
ok(replyFor("NETFLIX.COM 1590").includes("Netflix"), "1行だけの明細でも探す");
ok(normal.includes("見つかりませんでした") && !normal.includes("サブスク："), "規約の文章は規約として判定");
const termsWithName = replyFor("第1条（適用）\n本規約はNetflixの利用に適用されます。料金は返金しません。解約手数料はかかりません。第2条 以上。");
ok(!termsWithName.includes("見つかったサブスク"), "サービス名を含む規約でも規約として判定");
console.log(fail ? `${fail}件失敗` : "すべて成功"); process.exit(fail ? 1 : 0);
